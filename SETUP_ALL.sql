-- ========== chat ==========
create table if not exists public.chat_messages (
  id uuid primary key default gen_random_uuid(),
  client_id text not null,
  user_id uuid,
  player_name text not null,
  body text not null,
  created_at timestamptz not null default now()
);
alter table public.chat_messages enable row level security;
drop policy if exists "Public read chat_messages" on public.chat_messages;
create policy "Public read chat_messages" on public.chat_messages for select to anon, authenticated using (true);
drop policy if exists "Public insert chat_messages" on public.chat_messages;
create policy "Public insert chat_messages" on public.chat_messages for insert to anon, authenticated
  with check (
    char_length(client_id) between 8 and 64
    and char_length(player_name) between 1 and 12
    and char_length(body) between 1 and 80
  );

-- ========== replays (VID button) ==========
create table if not exists public.speedrun_replays (
  id bigint generated by default as identity primary key,
  run_id uuid,
  category text not null,
  time_ms integer not null check (time_ms > 0),
  player_name text not null check (char_length(player_name) between 3 and 12),
  frames jsonb not null,
  created_at timestamptz not null default now()
);
create index if not exists speedrun_replays_cat_time on public.speedrun_replays (category, time_ms asc);
create unique index if not exists speedrun_replays_run_id_uidx on public.speedrun_replays (run_id) where run_id is not null;
alter table public.speedrun_replays enable row level security;
drop policy if exists "Public read speedrun_replays" on public.speedrun_replays;
create policy "Public read speedrun_replays" on public.speedrun_replays for select to anon, authenticated using (true);
drop policy if exists "Public insert speedrun_replays" on public.speedrun_replays;
create policy "Public insert speedrun_replays" on public.speedrun_replays for insert to anon, authenticated
  with check (
    category in (
      'shark','jelly_white','chest','death','boat','full_inv','shark_cloak',
      'serpent','blowfish','megalodon','coins_10','coins_25','coins_100'
    )
    and time_ms > 0
    and char_length(player_name) between 3 and 12
    and jsonb_typeof(frames) = 'array'
  );
