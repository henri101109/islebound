create or replace function public.player_is_banned(
  p_name text,
  p_user_id uuid,
  p_client_id text,
  p_ip text
) returns boolean
language sql
stable
as $$
  select exists (
    select 1
    from public.player_bans b
    where (b.expires_at is null or b.expires_at > now())
      and (
        (b.user_id is not null and p_user_id is not null and b.user_id = p_user_id)
        or (b.client_id is not null and p_client_id is not null and b.client_id = p_client_id)
        or (b.ip is not null and p_ip is not null and b.ip = p_ip)
        or (
          b.name_norm is not null
          and p_name is not null
          and (
            upper(trim(p_name)) = upper(trim(b.name_norm))
            or split_part(upper(trim(p_name)), ' ', 1) = upper(trim(b.name_norm))
            or upper(trim(p_name)) like upper(trim(b.name_norm)) || ' %'
          )
        )
      )
  );
$$;

