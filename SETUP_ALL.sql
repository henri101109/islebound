-- Wipe known impossible Matteus fish WRs (~15s = cast-only cheats)
delete from public.speedrun_scores
where player_name = 'MATTEUS'
  and category in ('shark', 'jelly_white', 'chest', 'shark_cloak', 'blowfish', 'megalodon', 'serpent')
  and time_ms < 28000;
delete from public.speedrun_replays
where player_name = 'MATTEUS'
  and category in ('shark', 'jelly_white', 'chest', 'shark_cloak', 'blowfish', 'megalodon', 'serpent')
  and time_ms < 28000;

-- ========== scores ==========
create table if not exists public.speedrun_scores (
  id bigint generated by default as identity primary key,
  category text not null,
  time_ms integer not null check (time_ms > 0),
  player_name text not null check (char_length(player_name) between 3 and 12),
  created_at timestamptz not null default now()
);
alter table public.speedrun_scores add column if not exists user_id uuid;
alter table public.speedrun_scores add column if not exists run_id uuid;
alter table public.speedrun_scores add column if not exists is_account boolean not null default false;
create index if not exists speedrun_scores_cat_time on public.speedrun_scores (category, time_ms asc);
create unique index if not exists speedrun_scores_run_id_uidx on public.speedrun_scores (run_id) where run_id is not null;
alter table public.speedrun_scores enable row level security;
drop policy if exists "Public read speedrun_scores" on public.speedrun_scores;
create policy "Public read speedrun_scores" on public.speedrun_scores for select to anon, authenticated using (true);
drop policy if exists "Public insert speedrun_scores" on public.speedrun_scores;
drop policy if exists "Insert speedrun_scores guests or self" on public.speedrun_scores;
drop policy if exists "Insert speedrun_scores guests or accounts" on public.speedrun_scores;
create policy "Insert speedrun_scores guests or accounts"
  on public.speedrun_scores for insert to anon, authenticated
  with check (
    category in (
      'shark','jelly_white','chest','death','boat','full_inv','shark_cloak',
      'serpent','blowfish','megalodon','coins_10','coins_25','coins_100'
    )
    and time_ms > 0
    and char_length(player_name) between 3 and 12
    and ((user_id is null and is_account = false) or (user_id is not null))
  );

